// Середня цінність фігур у масиві
double getAverageValue(Piece** pieces, int count)
{
    if (count == 0)
    {
        return 0;
    }
    int sum = 0;
    for (int i = 0; i < count; i++)
    {
        sum += pieces[i]->getValue();
    }
    return sum / count;                   // ВИПРАВТЕ: ділення цілочисельне
}

