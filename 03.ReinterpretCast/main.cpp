#include <iostream>
#include <windows.h>

using namespace std;

/*
==========================================================================================================================================
                                                       Оператор reinterpret_cast
==========================================================================================================================================

  REINTERPRET_CAST — наказує компілятору розглядати ті самі байти пам'яті як значення іншого типу.
  Нічого не перетворює і не перевіряє.

  Застосовується в низькорівневому коді: окремі байти, двійкові файли, мережа, обладнання.
  Результат залежить від платформи (порядок байтів, розміри типів).

*/

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    int number = 258;                         // 258 = 1 * 256 + 2
    unsigned char* bytes = reinterpret_cast<unsigned char*>(&number);

    cout << "Байти числа 258: ";
    for (int i = 0; i < 4; i++)               // sizeof(int) == 4
    {
        cout << static_cast<int>(bytes[i]) << " ";   // без static_cast cout виведе символ, а не число
    }
    cout << endl;                             // 2 1 0 0: процесори x86 зберігають молодший байт першим

    return 0;
}

/*
==========================================================================================================================================
                                                  ІНСАЙТИ / ЛАЙФХАКИ / BEST PRACTICES
==========================================================================================================================================

  1. reinterpret_cast ви зустрінете в темі «Потоки»: запис числа в двійковий файл —
     file.write(reinterpret_cast<const char*>(&value), sizeof(value)). Файл отримує саме ці байти.

  2. Такий файл, записаний на одній платформі, може неправильно прочитатися на іншій: порядок байтів і розміри типів
     можуть відрізнятися. У прикладному коді reinterpret_cast трапляється рідко.
*/
